# ============================================================
# Part 1: 负反馈 vs 正反馈 — 一维演示
# ============================================================
P("Part 1: 负反馈 vs 正反馈 (一维)")
P("-"*70)

def feedback_system(x0, gain, n_steps=20):
    """
    负反馈 (gain > 0): x(t+1) = x - gain·x = (1-gain)·x  → 衰减
    正反馈 (gain < 0): x(t+1) = x + |gain|·x = (1+|gain|)·x → 发散
    """
    x = x0
    traj = [x]
    for _ in range(n_steps):
        x = x + (-gain) * x  # 负反馈: gain>0 → x 减小; 正反馈: gain<0 → x 增大
        traj.append(x)
        if abs(x) > 1e10: break
    return traj

print(f"\n{'反馈类型':<24}{'初始 x':>10}{'最终 x':>14}{'性质':<20}")
print("-"*68)
for name, gain in [("强负反馈 (gain=0.5)", 0.5),
                    ("弱负反馈 (gain=0.1)", 0.1),
                    ("临界 (gain=0)",      0.0),
                    ("弱正反馈 (gain=-0.1)", -0.1),
                    ("强正反馈 (gain=-0.5)", -0.5)]:
    traj = feedback_system(1.0, gain)
    final = traj[-1]
    nature = "稳定衰减" if gain > 0 else ("保持" if gain == 0 else "发散")
    print(f"{name:<24}{1.0:>10.2f}{final:>14.4e}    {nature}")

P("""
观察:
- 负反馈: x → 0 (系统回到稳态)
- 正反馈: x → ∞ (系统发散, 如雪崩/指数增长)
- 临界: 保持
""")


# Part 2: 洛伦兹吸引子 — 确定性混沌
# ============================================================
P("="*70)
P("Part 2: 洛伦兹吸引子 (1963) — 3 个微分方程涌现混沌")
P("-"*70)
P()
P("Lorenz 方程:")
P("  dx/dt = σ(y - x)         σ=10  (Prandtl 数)")
P("  dy/dt = x(ρ - z) - y     ρ=28  (Rayleigh 数)")
P("  dz/dt = xy - βz          β=8/3 (几何参数)")
P()

def lorenz_step(state, dt=0.01, sigma=10, rho=28, beta=8/3):
    x, y, z = state
    dx = sigma * (y - x)
    dy = x * (rho - z) - y
    dz = x * y - beta * z
    return np.array([x + dx*dt, y + dy*dt, z + dz*dt])

def simulate_lorenz(state0, n_steps=5000, dt=0.01):
    s = np.array(state0)
    traj = [s.copy()]
    for _ in range(n_steps):
        s = lorenz_step(s, dt)
        traj.append(s.copy())
    return np.array(traj)

# 跑两个相近初始条件
traj1 = simulate_lorenz([1.0, 1.0, 1.0])
traj2 = simulate_lorenz([1.001, 1.0, 1.0])  # 仅差 0.001

# 算发散速度
diffs = np.linalg.norm(traj1 - traj2, axis=1)
print(f"两个初始条件差 0.001 的轨迹:")
print(f"\n{'step':<8}{'轨迹1 x':>12}{'轨迹2 x':>12}{'差异 |Δ|':>14}")
print("-"*46)
for step in [0, 10, 100, 500, 1000, 2000, 5000]:
    print(f"{step:<8}{traj1[step, 0]:>+12.4f}{traj2[step, 0]:>+12.4f}{diffs[step]:>14.4f}")

# 估算 Lyapunov 指数 (混沌标志)
lyapunov_est = math.log(diffs[1000] / diffs[1]) / 1000
print(f"\n估算 Lyapunov 指数: λ ≈ {lyapunov_est:.4f} > 0 → 混沌!")

P("""
关键观察:
- step 0: 差异 0.001 (微小扰动)
- step 1000: 差异 ~10 (放大 10000 倍!)
- 这就是 [蝴蝶效应]: 初始小扰动 → 长期大差异

Lyapunov 指数 λ > 0 是混沌的数学标志:
- 误差按 e^(λt) 增长
- 长期预测不可能 (但短期可以)

Lorenz 用这个发现开创了 [混沌理论] (1963).
""")


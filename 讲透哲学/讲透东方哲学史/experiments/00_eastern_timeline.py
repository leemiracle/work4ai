CIV_ORDER = ["印度", "伊斯兰", "日本", "跨文明"]
ERAS = [  # (标签, 下界, 上界) 闭区间;吠陀与轴心期含 -200(《薄伽梵歌》传统断代)
    ("吠陀与轴心期", -1500, -200),
    ("古典与中世", -199, 1199),
    ("近世", 1200, 1799),
    ("近现代", 1800, 2100),
]
AXIAL = (-800, -200)      # 轴心期窗口(断言①)
JP_MODERN = (1868, 1945)  # 日本西方化窗口(断言②)


def era_of(year):
    for label, lo, hi in ERAS:
        if lo <= year <= hi:
            return label
    return "?"


def density(events, lo, hi):
    """窗口内事件数 / 跨度(百年);无 0 年修正:跨公元前窗口按含端点年数计。"""
    n = sum(1 for e in events if lo <= e[0] <= hi)
    span = hi - lo + 1
    return n, n / span * 100


def main():
    print("=" * 72)
    print("东方哲学史编年:76 条里程碑 · 文明×大时代矩阵")
    print("=" * 72)

    # 矩阵:行=大时代,列=文明
    print(f"\n{'大时代':<8}{'印度':>4}{'伊斯兰':>6}{'日本':>4}{'跨文明':>6}{'合计':>5}")
    for label, _, _ in ERAS:
        row = [e for e in TIMELINE if era_of(e[0]) == label]
        cells = [sum(1 for e in row if e[1] == c) for c in CIV_ORDER]
        print(f"{label:<8}{cells[0]:>5}{cells[1]:>7}{cells[2]:>5}{cells[3]:>7}{len(row):>5}")

    civ_total = {c: sum(1 for e in TIMELINE if e[1] == c) for c in CIV_ORDER}
    print("\n文明总计:", "  ".join(f"{c}×{civ_total[c]}" for c in CIV_ORDER))

    # ── 断言①:轴心期多文明共振 ──────────────────────────────
    ax = [e for e in TIMELINE if AXIAL[0] <= e[0] <= AXIAL[1]]
    ax_civs = {e[1] for e in ax}
    ax_india = sum(1 for e in ax if e[1] == "印度")
    print("\n" + "=" * 72)
    print(f"断言① 轴心期(前{abs(AXIAL[0])}-前{abs(AXIAL[1])})共振检验:")
    print(f"  窗口内事件 {len(ax)} 条,文明 {sorted(ax_civs)}(印度×{ax_india} + 伊朗前史×1)")
    for _, c, p, t in ax:
        mark = "●" if c == "印度" else "○"
        print(f"    {mark} {c:<4}{p:<12}{t[:26]}")
    assert len(ax_civs) >= 2 and ax_india >= 6, "轴心期应有≥2文明同时发问,且印度为主动脉"
    print("  断言通过:轴心期内东方数据集呈多文明共振(印度主动脉+伊朗前史)✓")
    print("  ——雅斯贝尔斯「三文明共振」(印/中/希)的另两翼由同波兄弟家族承载(见脚本头注)")

    # ── 断言②:近代日本西方化窗口密度 ─────────────────────────
    jp = [e for e in TIMELINE if e[1] == "日本"]
    n_mod, d_mod = density(jp, *JP_MODERN)
    n_pre, d_pre = density(jp, 552, 1867)
    ratio = d_mod / d_pre
    print(f"\n断言② 日本线密度检验:")
    print(f"  江户及以前(552-1867):{n_pre} 件/{1315} 年 = {d_pre:.2f} 件/百年")
    print(f"  西方化窗口(1868-1945):{n_mod} 件/{JP_MODERN[1]-JP_MODERN[0]+1} 年 = {d_mod:.2f} 件/百年")
    print(f"  密度比 = {ratio:.0f}× —— 明治「哲学」译名之后,事件密度换挡")
    assert ratio > 5, "明治-昭和窗口密度应高一个量级"
    for _, _, p, t in [e for e in jp if JP_MODERN[0] <= e[0] <= JP_MODERN[1]]:
        print(f"    ▲ {p:<10}{t[:30]}")

    # ── 断言③:三线覆盖 + 传播链在场 ─────────────────────────
    assert civ_total["印度"] >= 20 and civ_total["伊斯兰"] >= 12, "三条河每条都该成河"
    assert civ_total["日本"] >= 20 and civ_total["跨文明"] >= 6, "日本线与传播线不应缺席"
    years = {e[0] for e in TIMELINE}

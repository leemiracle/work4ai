# 时期切片的声明区间(供完整性校验;文艺复兴与十七十八世纪以 1600 为共享界)
PERIOD_SPAN = {
    "古希腊罗马": (-585, 529),
    "中世纪": (480, 1453),
    "文艺复兴": (1453, 1600),
    "十七十八世纪": (1600, 1780),
    "德国古典": (1781, 1831),
}
PERIOD_ORDER = ["古希腊罗马", "中世纪", "文艺复兴", "十七十八世纪", "德国古典"]


# ---------------------------------------------------------------- 工具函数
def slice_by_period():
    """按时期切片,期内按年代排序——家族树六支中五支的数据现场(俄国支不在段内)。"""
    return {p: sorted([e for e in EVENTS if e[1] == p]) for p in PERIOD_ORDER}


def density(evts, width=100):
    """所有宽度=width 年的滑动窗口中的最大事件数及其窗口。"""
    years = [e[0] for e in evts]
    lo, hi = min(years), max(years)
    best_n, best_w = -1, None
    for start in range(lo, hi - width + 2):
        n = sum(1 for y in years if start <= y < start + width)
        if n > best_n:
            best_n, best_w = n, (start, start + width)
    return best_n, best_w


def concept_set(period):
    return {e[4] for e in EVENTS if e[1] == period}


# ---------------------------------------------------------------- 报告与断言
def main():
    print("西方哲学大事编年(前585-1831,共 %d 条)" % len(EVENTS))
    print("=" * 72)

    for p in PERIOD_ORDER:
        rows = slice_by_period()[p]
        span = PERIOD_SPAN[p]
        rate = len(rows) / ((span[1] - span[0]) / 100.0)
        print("\n【%s】(%s~%s,%d 条,密度 %.1f 条/百年)"
              % (p, span[0], span[1], len(rows), rate))
        for y, _, figure, event, concept in rows:
            print("  %6s %-18s %-32s [%s]" % (y, figure, event, concept))

    print("\n" + "=" * 72)
    print("检验 A:两个密度峰(100 年滑动窗口)")

    ancient_bc = [e for e in EVENTS if e[0] < 0]
    bc_n, bc_w = density(ancient_bc)
    print("A1 古典峰:公元前最大窗口 %s = %d 条" % (bc_w, bc_n))
    assert bc_n >= 7, "古典峰应≥7 条"
    assert -500 <= bc_w[0] <= -350, "古典峰应落在前5-前4世纪(雅典世纪)"

    g_n, g_w = density(EVENTS)
    print("A2 近代峰:全史最大窗口 %s = %d 条" % (g_w, g_n))
    assert g_n >= 20 and g_w[0] >= 1700, "全史最大密度应在启蒙晚期-德古段"

    medieval = [e for e in EVENTS if 524 <= e[0] <= 1450]
    m_n, m_w = density(medieval)
    print("A3 对照低谷:中世纪最大窗口 %s = %d 条" % (m_w, m_n))
    assert m_n <= 5, "中世纪任意百年窗口应≤5 条"

    modern = sum(1 for e in EVENTS if 1600 <= e[0] <= 1831)
    antiquity = sum(1 for e in EVENTS if e[0] <= 529)
    print("A4 惊人事实:1600-1831(231 年)=%d 条 > 前585-529(1114 年)=%d 条"
          % (modern, antiquity))
    assert modern > antiquity, "近代密度反超古代是本数据集的核心事实"

    print("\n检验 B:概念术语随时期更替(相邻时期标签集合)")
    for a, b in zip(PERIOD_ORDER, PERIOD_ORDER[1:]):
        common = concept_set(a) & concept_set(b)
        union = concept_set(a) | concept_set(b)
        jaccard = len(common) / len(union) if union else 0.0
        print("  %s × %s:交集=%s,Jaccard=%.2f" % (a, b, sorted(common) or "∅", jaccard))
        assert not common, "相邻时期概念标签不应复用(换弹药):%s" % sorted(common)

    print("\n检验 C:完整性")
    assert len(EVENTS) >= 70, "编年应≥70 条(现 %d)" % len(EVENTS)
    assert EVENTS[0][2] == "泰勒斯" and EVENTS[0][0] == -585, "首条应为泰勒斯(前585)"
    assert EVENTS[-1][2].startswith("黑格尔") and EVENTS[-1][0] == 1831, "末条应为黑格尔(1831)"
    tags = [e[4] for e in EVENTS]
    assert len(tags) == len(set(tags)), "概念标签应全表唯一(一个标签=一个户口)"
    for p in PERIOD_ORDER:  # 期内升序即可(480-529 古代/中世纪共享过渡带,允许交叉)
        ys = [e[0] for e in EVENTS if e[1] == p]
        assert ys == sorted(ys), "时期 %s 内应按年代升序" % p
    for y, p, _, _, _ in EVENTS:
        lo, hi = PERIOD_SPAN[p]
        assert lo <= y <= hi, "事件 %s(%s)越出时期 %s 声明区间" % (y, p, (lo, hi))
    print("  共 %d 条;首尾/期内序/区间/标签唯一 全部通过" % len(EVENTS))

    print("\n全部断言通过:哲学史=雅典喷发 + 千年深流 + 近代大喷发;每代换弹药。")
    print("口径声明:密度结论依赖'大事'口径——换口径即换结论(见脚本头部纪律声明)。")


if __name__ == "__main__":
    main()

# -*- coding: utf-8 -*-
"""
亚洲王朝-政体变迁统计（走廊1：王朝政体统计）
对应章：讲透亚洲史/04-亚洲史转代码.md

数据口径：2026-09 模型知识核对；取通行断代，寿命=止年-起年；
日本 660 为传统纪年起点（神武即位），实证可考期自 5-6 世纪；
室利佛逝连续性有争议，仅列不验。如与权威年表不符以权威为准。
"""
from statistics import mean

# 中国大一统王朝（名, 起, 止）
CHINA_UNIFIED = [
    ("秦", -221, -206), ("西汉", -202, 8), ("东汉", 25, 220),
    ("西晋", 265, 316), ("隋", 581, 618), ("唐", 618, 907),
    ("两宋", 960, 1279), ("元", 1271, 1368), ("明", 1368, 1644),
    ("清", 1644, 1912),
]

# 日本（传统纪年；万世一系=0 次改朝换代）
JAPAN = [("日本天皇制", 660, 2026)]

# 其他亚洲主要王朝（名, 起, 止, 区域）
OTHERS = [
    ("奥斯曼", 1299, 1922, "西亚"), ("朝鲜王朝", 1392, 1897, "东北亚"),
    ("莫卧儿", 1526, 1857, "南亚"), ("帖木儿", 1370, 1507, "中亚"),
    ("满者伯夷", 1293, 1527, "东南亚"), ("室利佛逝", 650, 1288, "东南亚"),
]

# 亚洲主要君主制的终结（名, 终结年）
MONARCHY_END = [
    ("莫卧儿帝国", 1857), ("大韩帝国", 1910), ("大清帝国", 1912),
    ("奥斯曼苏丹制", 1922), ("波斯卡扎尔王朝", 1925), ("尼泊尔王国", 2008),
]

def main():
    life = {n: e - s for n, s, e in CHINA_UNIFIED}

    # 断言1：中国大一统王朝"三百年天花板"——全部<320年；≥250年恰4个
    assert max(life.values()) == 319 < 320, life
    assert sum(1 for v in life.values() if v >= 250) == 4, life
    over = [n for n, v in life.items() if v >= 250]
    print(f"[1] 中国大一统王朝寿命上限 {max(life.values())} 年（两宋），"
          f"≥250 年者恰 4 个：{'、'.join(over)}；均值 {mean(life.values()):.0f} 年")

    # 断言2：同期改朝换代次数——中国 9 次 vs 日本 0 次
    transitions_cn = len(CHINA_UNIFIED) - 1
    transitions_jp = len(JAPAN) - 1
    span_cn = 1912 - (-221)
    assert transitions_cn == 9 and transitions_jp == 0
    print(f"[2] 前221-1912：中国改朝换代 {transitions_cn} 次"
          f"（平均每 {span_cn // transitions_cn} 年一次）；日本 {transitions_jp} 次"
          f"——'万世一系'与中国'周期律'是同一片海的两个海岸")

    # 断言3："三百年天花板"非亚洲通则——奥斯曼≈2倍中国最长王朝
    otto = 1922 - 1299
    joseon = 1897 - 1392
    assert otto >= 1.9 * 319 and joseon > 319, (otto, joseon)
    print(f"[3] 奥斯曼 {otto} 年（≈中国最长王朝 {otto / 319:.1f} 倍）、"
          f"朝鲜王朝 {joseon} 年——天花板是中国式改朝机制的特征，非普世规律")

    # 断言4：君主制终结的窗口性——1910-1922 密集终结
    w1 = [n for n, y in MONARCHY_END if 1910 <= y <= 1922]
    w2 = [n for n, y in MONARCHY_END if 1857 <= y <= 1925]
    assert len(w1) >= 3 and len(w2) >= 5, (w1, w2)
    print(f"[4] 1910-1922 终结：{'、'.join(w1)}；1857-1925 窗口共 {len(w2)} 例"
          f"——亚洲旧君主制在一代人内清盘（与欧洲四帝国解体同步，见欧洲史家族实验）")

    # 断言5：万世一系的量化——天皇制跨度（传统纪年）≥4倍中国最长王朝
    jp_span = 2026 - 660
    assert jp_span >= 4 * 319, jp_span
    print(f"[5] 日本天皇制跨度（传统纪年）{jp_span} 年 ≈ 中国最长王朝 {jp_span / 319:.1f} 倍"
          f"——君主制'连续性'的极端离群值（传统纪年含半传说期，实证可考自 5-6 世纪起）")

    print("\n全部断言通过 ✓ （王朝统计=把史学习语放进单元测试）")

if __name__ == "__main__":
    main()

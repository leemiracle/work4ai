# -*- coding: utf-8 -*-
"""
美洲 35 国独立年表名录统计（走廊2：名录统计）
对应章：讲透历史学/讲透美洲史/04-美洲史转代码.md

数据：西半球 35 个主权国家的独立年份与殖民母国。
口径：加拿大 1867=联邦成立（渐进独立）；委内瑞拉取 1811 首次宣告
（1821 年巩固）；多米尼加 1844=自海地分离（西班牙殖民遗产）；
巴拿马 1903=自哥伦比亚分离（美国支持）。数据口径：2026-09 模型知识核对。
"""
from collections import Counter

# (国家, 独立年, 殖民母国)
ROWS = [
    ("美国", 1776, "英国"), ("加拿大", 1867, "英国"), ("墨西哥", 1821, "西班牙"),
    ("危地马拉", 1821, "西班牙"), ("洪都拉斯", 1821, "西班牙"),
    ("萨尔瓦多", 1821, "西班牙"), ("尼加拉瓜", 1821, "西班牙"),
    ("哥斯达黎加", 1821, "西班牙"), ("巴拿马", 1903, "西班牙(自哥伦比亚分离)"),
    ("伯利兹", 1981, "英国"), ("古巴", 1902, "西班牙(经美西战争)"),
    ("海地", 1804, "法国"), ("多米尼加", 1844, "西班牙(自海地分离)"),
    ("牙买加", 1962, "英国"), ("特立尼达和多巴哥", 1962, "英国"),
    ("巴巴多斯", 1966, "英国"), ("巴哈马", 1973, "英国"),
    ("格林纳达", 1974, "英国"), ("多米尼克", 1978, "英国"),
    ("圣卢西亚", 1979, "英国"), ("圣文森特和格林纳丁斯", 1979, "英国"),
    ("安提瓜和巴布达", 1981, "英国"), ("圣基茨和尼维斯", 1983, "英国"),
    ("哥伦比亚", 1819, "西班牙"), ("委内瑞拉", 1811, "西班牙"),
    ("厄瓜多尔", 1822, "西班牙"), ("秘鲁", 1821, "西班牙"),
    ("玻利维亚", 1825, "西班牙"), ("智利", 1818, "西班牙"),
    ("阿根廷", 1816, "西班牙"), ("巴拉圭", 1811, "西班牙"),
    ("乌拉圭", 1830, "西班牙"), ("圭亚那", 1966, "英国"),
    ("苏里南", 1975, "荷兰"), ("巴西", 1822, "葡萄牙"),
]

def main():
    # 断言1：35 国、无重名
    assert len(ROWS) == 35, len(ROWS)
    assert len(set(r[0] for r in ROWS)) == 35
    print(f"[1] 西半球主权国家 {len(ROWS)} 个")

    ys = sorted(y for _, y, _ in ROWS)

    # 断言2：最早独立=美国 1776；海地 1804=第一个黑人共和国（奴隶革命建国）
    first = min(ROWS, key=lambda r: r[1])
    assert first[0] == "美国" and first[1] == 1776, first
    haiti = [r for r in ROWS if r[0] == "海地"][0]
    assert haiti[1] == 1804, haiti
    print(f"[2] 最早独立：{first[0]} {first[1]}；海地 {haiti[1]} —— "
          "世界史上唯一由奴隶革命建国的国家")

    # 断言3：西语美洲独立波 1810-1825 恰 14 国（多米尼加/乌拉圭在窗外）
    wave = sorted(n for n, y, p in ROWS
                  if p.startswith("西班牙") and 1810 <= y <= 1825)
    assert len(wave) == 14, wave
    print(f"[3] 西语美洲独立波 1810-1825 共 {len(wave)} 国 —— 玻利瓦尔与圣马丁的双线解放")

    # 断言4：1962-1983 加勒比-圭亚那-伯利兹波恰 13 国（超三分之一）
    late = sorted(n for n, y, _ in ROWS if y >= 1962)
    assert len(late) == 13, late
    print(f"[4] 1962-1983 独立 {len(late)} 国（{len(late)/35:.0%}）—— "
          "美洲去殖民的大头不在 19 世纪")

    # 断言5：殖民母国计数 西 18 / 英 14 / 法 1 / 荷 1 / 葡 1
    powers = Counter(r[2].split("(")[0] for r in ROWS)
    assert powers == {"西班牙": 18, "英国": 14, "法国": 1, "荷兰": 1, "葡萄牙": 1}, powers
    print(f"[5] 殖民母国分布 = {dict(powers)} —— 葡萄牙帝国在美洲只留下巴西一国")

    # 断言6：独立年份中位数 = 1830（乌拉圭）——"美洲=19 世纪独立"的直觉校准
    median = ys[len(ys) // 2]  # 35 个数取第 18 个
    assert median == 1830, median
    print(f"[6] 独立年份中位数 = {median} —— 但下四分位之后还有 13 国要等到 1962 年后")

    print("\n全部断言通过 ✓ （名录统计=走廊2：35 国=三波独立的叠加结构）")

if __name__ == "__main__":
    main()

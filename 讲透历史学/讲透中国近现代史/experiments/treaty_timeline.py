# -*- coding: utf-8 -*-
"""
近代条约年表：把"条约体系"从形容词变成可复算结构
（对应章：00/03/04）家族：讲透中国近现代史（GB/T 77035）

口径声明（计量史学第一条纪律：口径透明）：
- 选取 1840-1912 间"结构性影响"代表性条约（非全量编目；全量见
  王铁崖《中外旧约章汇编》）。
- 赔款单位一律取"万两白银·本金"：南京条约赔款为 2100 万银元
  （币制不同）记 None；伊犁条约为 900 万卢布记 None；马关本金
  2 亿两（赎辽费 3000 万两另计）；辛丑本金 4.5 亿两（本息合计
  约 9.8 亿两，39 年付清——利息不计入本金断言）。
- "战争-条约锁步"取四次大战的标志性条约：南京(1842)、北京(1860)、
  马关(1895)、辛丑(1901)。
数据口径：2026-09 模型知识核对；如与《中外旧约章汇编》不符以汇编为准。
"""

# (条约, 签约年, 赔款本金万两 or None, 注)
TREATIES = [
    ("南京条约", 1842, None, "赔款2100万银元(非银两口径)；五口通商"),
    ("望厦条约", 1844, None, "中美：协定关税+治外法权雏形"),
    ("黄埔条约", 1844, None, "中法：传教条款"),
    ("瑷珲条约", 1858, None, "割外兴安岭以南60万km²"),
    ("天津条约", 1858, 400, "英法各200万两；长江通商"),
    ("北京条约", 1860, 800, "天津赔款倍增；割九龙；开天津"),
    ("伊犁条约", 1881, None, "赔款900万卢布(非银两口径)"),
    ("马关条约", 1895, 20000, "割台湾澎湖；另收赎辽费3000万两"),
    ("辛丑条约", 1901, 45000, "本金4.5亿两；本息合计约9.8亿两"),
]

# 四次大对外战争：(战争, 起年, 终年, 标志性条约)
WARS = [
    ("第一次鸦片战争", 1840, 1842, "南京条约"),
    ("第二次鸦片战争", 1856, 1860, "北京条约"),
    ("甲午战争",     1894, 1895, "马关条约"),
    ("八国联军侵华", 1900, 1901, "辛丑条约"),
]


def main():
    years = {t[0]: t[1] for t in TREATIES}

    # 断言1：近代总长 1840→1949 含头尾恰 110 年
    assert 1949 - 1840 + 1 == 110
    print("[1] 1840→1949 含头尾共 110 年（'一一零年近代史'）")

    # 断言2：战争-条约锁步——标志性条约全部签于战争结束同年
    for war, y0, y1, treaty in WARS:
        assert years[treaty] == y1, (war, treaty)
        assert y0 < y1 and y1 - y0 <= 4
    print("[2] 四次大战条约锁步：南京1842 / 北京1860 / 马关1895 / 辛丑1901"
          "——条约全部签于战争结束同年，无一例外")

    # 断言3：赔款本金（万两）单调爆涨，辛丑 = 马关 × 2.25
    seq = [(t[0], t[2]) for t in TREATIES if t[2] is not None]
    vals = [v for _, v in seq]
    assert vals == sorted(vals) and len(set(vals)) == len(vals)
    assert vals == [400, 800, 20000, 45000], vals
    assert 45000 == 2.25 * 20000 and 800 == 2 * 400
    print(f"[3] 赔款本金序列 {dict(seq)}（万两）——"
          "北京翻倍、马关×25、辛丑再×2.25：条约体系的'许可费'曲线")

    # 断言4：条约密度峰值 = 3 件/3年窗；1858-1860（瑷珲、天津、北京）达峰
    ys = [t[1] for t in TREATIES]
    counts = {y: sum(1 for x in ys if y <= x < y + 3)
              for y in range(1840, 1912)}
    peak = max(counts.values())
    peak_starts = [y for y, c in counts.items() if c == peak]
    assert peak == 3 and 1858 in peak_starts, (peak, peak_starts)
    print(f"[4] 三年滑窗签约密度峰值 = {peak} 件/3年，达峰起点 {peak_starts}"
          "（1842-44 战后补约窗与 1858-60 二次鸦片战争窗并列）")

    # 断言5：条约体系约一甲子成形；辛丑后 10 年帝国崩塌
    assert 1901 - 1842 == 59 and 1911 - 1901 == 10
    print("[5] 南京(1842)→辛丑(1901) = 59 年≈一甲子建成条约体系；"
          "辛丑→辛亥(1911) = 10 年")

    # 断言6：分期自检——旧民主主义 79 年 + 新民主主义 30 年
    old, new = 1919 - 1840, 1949 - 1919
    assert (old, new) == (79, 30) and old + new == 1949 - 1840
    print(f"[6] 旧民主主义革命 {old} 年 + 新民主主义革命 {new} 年 = "
          f"跨度 {old + new} 年（含头尾 110）")

    print("\n全部断言通过 ✓ （条约数据化=走廊1：把外交史变成可验证结构）")


if __name__ == "__main__":
    main()

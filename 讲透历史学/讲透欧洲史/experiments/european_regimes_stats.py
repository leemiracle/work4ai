# -*- coding: utf-8 -*-
"""
欧洲政体变迁编年统计（走廊1：政体变迁编年）
对应章：讲透欧洲史/04-欧洲史转代码.md

数据口径：2026-09 模型知识核对；君主制/帝国终结年取政体法律终结
（退位/废除），非国家消亡；欧盟按实际生效成员数；1793/1940 等宪法
按文本存在计（1793 未实施）。如与权威年表不符以权威为准。
"""
EU = [
    # (年, 变动数, 加入后成员数, 事件)
    (1952, 6, 6, "煤钢共同体六国"), (1973, 3, 9, "英国/爱尔兰/丹麦"),
    (1981, 1, 10, "希腊"), (1986, 2, 12, "西班牙/葡萄牙"),
    (1995, 3, 15, "奥地利/瑞典/芬兰"), (2004, 10, 25, "东扩十国"),
    (2007, 2, 27, "保加利亚/罗马尼亚"), (2013, 1, 28, "克罗地亚"),
    (2020, -1, 27, "英国脱欧"),
]

EMPIRE_END = [
    ("俄罗斯帝国", 1917, "二月革命，罗曼诺夫终结"),
    ("德意志帝国", 1918, "十一月革命，威廉二世退位"),
    ("奥匈帝国", 1918, "战败解体，共和国宣告"),
    ("奥斯曼帝国", 1922, "苏丹制废除"),
]

REV_1848 = [
    "法兰西", "普鲁士", "奥地利（维也纳）", "匈牙利", "意大利诸邦",
    "德意志诸邦（巴伐利亚/巴登等）", "波兰（波兹南）", "瓦拉几亚",
    "摩尔达维亚", "丹麦",
]

# 2026 欧洲君主制国家（含共治公国）；欧洲主权国家约 44 个（常用口径）
MONARCHIES_2026 = ["英国", "西班牙", "荷兰", "比利时", "丹麦", "瑞典", "挪威",
                   "卢森堡", "摩纳哥", "列支敦士登", "安道尔", "梵蒂冈"]
EUROPE_STATES_2026 = 44

# 1815 维也纳体系：主要大国（除瑞士外皆为君主制）
MAJOR_1815 = ["英国", "法国", "奥地利", "普鲁士", "俄国", "西班牙", "葡萄牙",
              "瑞典", "丹麦", "荷兰", "瑞士"]  # 仅末者为共和国
MONARCHICAL_1815 = len(MAJOR_1815) - 1

FR_CONSTITUTIONS = [1791, 1793, 1795, 1799, 1804, 1814, 1830, 1848,
                    1852, 1875, 1940, 1946, 1958]

def main():
    # 断言1：四帝国解体全部落在1917-1922窗口，其中1918年两例
    years = [y for _, y, _ in EMPIRE_END]
    assert all(1917 <= y <= 1922 for y in years), years
    assert years.count(1918) == 2, years
    print(f"[1] 四帝国解体年 = {sorted(years)}——五年窗口内清盘，"
          f"1918 年双杀（德/奥匈）：'旧欧洲'的清算日")

    # 断言2：1848"人民之春"波及≥10个领土单位
    assert len(REV_1848) >= 10
    print(f"[2] 1848 革命波及 {len(REV_1848)} 个领土单位"
          f"（前奏：1847 瑞士分离同盟战争）——一次欧洲范围的共振")

    # 断言3：欧盟扩员序列——2004单批+10为史上最大；峰值28；现状27
    max_intake = max(EU, key=lambda r: r[1])
    assert max_intake[1] == 10 and max_intake[0] == 2004
    assert max(r[2] for r in EU) == 28
    assert EU[-1][2] == 27
    chain = "→".join(str(r[2]) for r in EU)
    print(f"[3] 欧盟成员序列 {chain}；单批最大扩员 {max_intake[1]} 国"
          f"（{max_intake[0]} 年），峰值 28（2013-2020），现 27")

    # 断言4：君主制占比翻转——1815主要大国>90% → 2026全欧约27%
    r1815 = MONARCHICAL_1815 / len(MAJOR_1815)
    r2026 = len(MONARCHIES_2026) / EUROPE_STATES_2026
    assert r1815 > 0.9, r1815
    assert 0.20 < r2026 < 0.35, r2026
    print(f"[4] 欧洲君主制占比：1815 主要大国 {r1815:.0%} → "
          f"2026 全欧 {len(MONARCHIES_2026)}/{EUROPE_STATES_2026}≈{r2026:.0%}"
          f"——两个世纪的政体翻转")

    # 断言5：法国政体钟摆——1789-1958十三部宪法，平均约13.9年一部
    n = len(FR_CONSTITUTIONS)
    avg = (1958 - 1791) / (n - 1)
    assert n >= 12 and avg < 15, (n, avg)
    print(f"[5] 法国 1791-1958 共 {n} 部宪法文本，平均每 {avg:.1f} 年一部"
          f"——'政体钟摆'不是修辞是频率")

    print("\n全部断言通过 ✓ （政体编年=把政治史骨架变成可查询数据）")

if __name__ == "__main__":
    main()

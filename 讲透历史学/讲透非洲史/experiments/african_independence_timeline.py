def main():
    # 断言1：恰 54 国（非盟成员国数；不含撒哈拉民主阿拉伯共和国争议席位）
    assert len(ROWS) == 54, len(ROWS)
    names = [r[0] for r in ROWS]
    assert len(set(names)) == 54, "国名重复"
    print(f"[1] 非洲独立年表共 {len(ROWS)} 国")

    dated = [(n, y) for n, y, _, _ in ROWS if y is not None]

    # 断言2：1960"非洲年"恰 17 国独立
    y1960 = sorted(n for n, y in dated if y == 1960)
    assert len(y1960) == 17, y1960
    print(f"[2] 1960 年独立 {len(y1960)} 国（'非洲年'：法属西非+赤道非洲集体独立）")

    # 断言3：独立年份中位数 = 1961（时间直觉校准器）
    ys = sorted(y for _, y in dated)
    median = ys[len(ys) // 2]  # 53 个有年份，取第 27 个
    assert median == 1961, median
    print(f"[3] 独立年份中位数 = {median} —— 一半非洲国家的主权年龄不到一位老人的一生")

    # 断言4：1950 年前已获独立/建国日期的恰为利比里亚、南非、埃及（埃塞俄比亚连续独立不计年）
    pre1950 = sorted(((n, y) for n, y in dated if y < 1950), key=lambda t: t[1])
    assert pre1950 == [("利比里亚", 1847), ("南非", 1910), ("埃及", 1922)], pre1950
    print(f"[4] 1950 年前已有独立日期者 = {[n for n, _ in pre1950]}"
          "（埃塞俄比亚 1896 阿杜瓦战胜意大利，保持连续独立）")

    # 断言5：殖民解放口径下最后独立的是纳米比亚 1990（分离口径另有 1993/2011）
    colonies = [(n, y) for n, y, _, k in ROWS if k == "colony"]
    last = max(colonies, key=lambda t: t[1])
    assert last == ("纳米比亚", 1990), last
    print(f"[5] 非洲最后一块殖民地：{last[0]} {last[1]}"
          "（厄立特里亚 1993、南苏丹 2011 为后殖民再组合，另计）")

    # 断言6：主管方计数——法国 20、英国 18，合计占七成
    powers = Counter((r[2].split("(")[0]) for r in ROWS if r[3] == "colony" or r[3] == "founded")
    assert powers["法国"] == 20 and powers["英国"] == 18, powers
    print(f"[6] 独立前夕主管方：法国 {powers['法国']} 国、英国 {powers['英国']} 国"
          f" —— 两国合计 {(powers['法国']+powers['英国'])/54:.0%}")

    # 断言7：1960 年代是独立高峰（模态年代）
    decades = Counter((y // 10) * 10 for _, y in dated)
    assert decades.most_common(1)[0] == (1960, decades[1960]), decades
    print(f"[7] 按年代分布 = {dict(sorted(decades.items()))}"
          f" → 模态年代 1960s（{decades[1960]} 国）")

    print("\n全部断言通过 ✓ （名录统计=走廊1：把'去殖民'变成可验证数据）")

if __name__ == "__main__":
    main()

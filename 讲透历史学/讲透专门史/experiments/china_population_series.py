# -*- coding: utf-8 -*-
"""
中国历代官方人口序列（走廊2：人口序列——计量史学最老的走廊与最深的陷阱）
对应章：讲透历史学/讲透专门史/04-专门史转代码.md

数据：历代官方户口统计中的"口"数（单位：万），口径列标明性质——
汉唐"口"接近总人口；宋"口"学界主流认为仅计男丁（何炳棣说）；
清 1741 后因摊丁入亩，数字从"丁"（税额单位）转为实际人口；
1600 为学界估计非官方数。数据口径：2026-09 模型知识核对，
均为断代史教科书常引数字；如与正史原文不符以原文为准。

史学要点：同一条曲线里不同区间的测量口径不同——
"户口≠人口"是本走廊的第一戒。
"""

# (年份, 朝代纪年, 官方口数/万, 口径)
ROWS = [
    (2,    "西汉元始二年",   5959.5, "census"),
    (157,  "东汉永寿三年",   5648.7, "census"),
    (280,  "西晋太康元年",   1616.4, "census"),
    (609,  "隋大业五年",     4602.0, "census"),
    (755,  "唐天宝十四载",   5291.9, "census"),
    (760,  "唐乾元三年",     1699.0, "census"),
    (1109, "北宋大观三年",   4673.5, "ding_only"),  # 口仅计男丁
    (1393, "明洪武二十六年", 6054.6, "census"),
    (1600, "明万历二十八年", 15000.0, "estimate"),  # 学界估计（何炳棣系）
    (1741, "清乾隆六年",     14341.2, "census"),
    (1790, "清乾隆五十五年", 30148.7, "census"),
    (1834, "清道光十四年",   40100.7, "census"),
    (1851, "清咸丰元年",     43216.4, "census"),
    (1953, "共和国首次普查", 58260.3, "census"),    # 大陆口径
]

def main():
    d = {r[0]: r for r in ROWS}

    # 断言1：西汉元始二年口数 ≈ 5959.5 万（《汉书·地理志》原文级数字）
    assert 5900 < d[2][2] < 6000, d[2]
    print(f"[1] 公元 2 年官方口数 {d[2][2]:.1f} 万 —— 中国人口史的第一个硬锚点")

    # 断言2：安史之乱 755→760 官方口数跌 ≥65%——登记崩塌≠人口崩塌
    drop = 1 - d[760][2] / d[755][2]
    assert drop >= 0.65, drop
    print(f"[2] 755→760 官方口数跌 {drop:.0%} —— 学界共识实际人口仅降一两成，"
          "跌掉的是课税登记体系")

    # 断言3：北宋 1109 官方口数 < 唐 755，而实际人口更多（宋"口"仅计男丁）
    assert d[1109][2] < d[755][2]
    print(f"[3] 1109 官方 {d[1109][2]:.0f} 万 < 755 官方 {d[755][2]:.0f} 万 —— "
          "宋'口'仅计男丁，实际人口学界估 1 亿级：口径断层最醒目处")

    # 断言4：1741→1790 清代官方人口翻番（摊丁入亩：'丁'从税额变人头）
    ratio = d[1790][2] / d[1741][2]
    assert ratio >= 2.0, ratio
    print(f"[4] 1741→1790 官方人口 {ratio:.2f} 倍 —— 统计口径革命（丁→人）"
          "+ 新大陆作物扩边的叠加读数")

    # 断言5：1851 达前现代峰值 >4.3 亿；1953 首次现代普查 ~5.83 亿
    assert d[1851][2] > 43000, d[1851]
    assert 57000 < d[1953][2] < 59000, d[1953]
    print(f"[5] 1851 峰值 {d[1851][2]/1e4:.2f} 亿 → 1953 首次普查 {d[1953][2]/1e4:.2f} 亿"
          " —— 两个数字之间隔着统计制度的一百年")

    # 断言6：清代连续登记段（1741→1851）单调上升
    qing = [r[2] for r in ROWS if 1741 <= r[0] <= 1851]
    assert qing == sorted(qing), qing
    print(f"[6] 1741-1851 官方序列单调上升（{len(qing)} 个登记点）—— "
          "清中期'人口奇迹'的数据面")

    print("\n全部断言通过 ✓ （人口序列=走廊2：先问口径，再谈曲线）")

if __name__ == "__main__":
    main()

def clean_text(text):
    """Clean up text: remove excessive whitespace but preserve structure."""
    # Remove footnote markers like [1], [2]
    text = re.sub(r'\[\d+\]', '', text)
    # Normalize whitespace
    text = re.sub(r'[ \t]+', ' ', text)
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text.strip()

def extract_article_header(text):
    """Extract title and date from article text."""
    lines = [l.strip() for l in text.split('\n') if l.strip()]
    if len(lines) >= 2:
        title = lines[0]
        # Look for date pattern like (一九二五年...)
        date_match = re.search(r'[（(](.+?)[)）]', ' '.join(lines[:5]))
        date = date_match.group(1) if date_match else ""
        return title, date
    return lines[0] if lines else "", ""

def find_key_paragraphs(text, keywords, max_paras=5):
    """Find paragraphs containing key terms."""
    paragraphs = [p.strip() for p in text.split('\n') if len(p.strip()) > 50]
    scored = []
    for p in paragraphs:
        score = sum(1 for kw in keywords if kw in p)
        if score > 0:
            scored.append((score, p))
    scored.sort(key=lambda x: -x[0])
    return [p for _, p in scored[:max_paras]]

def search_all_pages(pages, terms):
    """Find all pages mentioning any of the terms, return as (page_idx, context)."""
    results = []
    for i, p in enumerate(pages):
        for term in terms:
            if term in p['text']:
                pos = p['text'].index(term)
                ctx = p['text'][max(0,pos-20):pos+len(term)+20]
                results.append((i, term, len(p['text']), ctx.replace('\n',' ')))
                break
    return results


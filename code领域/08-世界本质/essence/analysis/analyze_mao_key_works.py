def generate_core_arguments(a):
    """Generate core arguments from extracted text."""
    s = []
    
    # Extract argument-like sentences from source texts
    args_found = []
    for src in a['sources']:
        text = src['text']
        paragraphs = [p.strip() for p in text.split('\n') if len(p.strip()) > 80]
        for p in paragraphs:
            # Look for argumentative patterns
            if any(kw in p for kw in ['是', '必须', '应当', '就是', '因为', '所以', '不是', '不能']):
                # Score by keyword density
                kw = get_keywords_for_work(a['id'])
                score = sum(1 for k in kw if k in p)
                if score >= 2 or len(p) > 150:
                    args_found.append((score, len(p), p, src['title'][:20]))
    
    # Deduplicate and sort
    seen = set()
    unique_args = []
    for score, length, p, src_title in sorted(args_found, key=lambda x: (-x[0], -x[1])):
        key = p[:50]
        if key not in seen:
            seen.add(key)
            unique_args.append((p, src_title))
        if len(unique_args) >= 5:
            break
    
    if unique_args:
        for i, (p, src_title) in enumerate(unique_args[:5]):
            # Truncate to reasonable length
            display = p[:400] + ('...' if len(p) > 400 else '')
            s.append(f"**论点{i+1}**（出处：《文集》·{src_title}）:")
            s.append(f"> {display}")
            s.append("")
    else:
        s.append("*从《文集》数据中未提取到足够的核心论点段落。参见上文历史背景中的分析。*")
        s.append("")
    
    return '\n'.join(s)


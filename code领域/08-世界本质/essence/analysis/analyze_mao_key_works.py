def analyze_work(work, pages):
    """Analyze a single work using available data."""
    result = {
        'title': work['title'],
        'year': work['year'],
        'id': work['id'],
        'alt_note': work.get('alt_note', ''),
        'is_full_article': work.get('is_full_article', False),
        'sources': [],
        'all_mentions': [],
    }
    
    # Search all pages for mentions
    mentions = search_all_pages(pages, work['search_terms'])
    result['all_mentions'] = mentions[:10]  # top mentions
    
    # Extract content from alt_pages
    for pg_idx in work['alt_pages']:
        if pg_idx < len(pages):
            text = clean_text(pages[pg_idx]['text'])
            header_title, date = extract_article_header(pages[pg_idx]['text'])
            result['sources'].append({
                'page': pg_idx,
                'title': header_title,
                'date': date,
                'text': text,
                'char_count': len(text),
                'first_3000': text[:3000],
            })
    
    return result


    if a['is_full_article']:
        s.append("> ✅ **本文以完整全文收入《毛泽东文集》**，以下分析基于完整原文。")
    else:
        s.append(f"> 📝 {a['alt_note']}")
    s.append("")
    
    # Historical background (based on knowledge + data)
    s.append("### 1. 历史背景")
    s.append("")
    s.append(generate_background(a))
    s.append("")
    
    # Extracted original text
    s.append("### 2. 《文集》中可获取的原文文献")
    s.append("")
    
    if a['sources']:
        for i, src in enumerate(a['sources']):
            s.append(f"#### 文献{i+1}：{src['title']}")
            if src['date']:
                s.append(f"**日期**: {src['date']}  ")
            s.append(f"**位置**: 文集第{src['page']+1}页 | **字数**: {src['char_count']:,}字")
            s.append("")
            s.append("**原文（前3000字）**:")
            s.append("")
            s.append("> " + src['first_3000'].replace('\n', '\n> '))
            s.append("")
            
            # Key paragraphs
            if i == 0:  # Only for primary source
                key_kw = get_keywords_for_work(a['id'])
                key_paras = find_key_paragraphs(src['text'], key_kw)

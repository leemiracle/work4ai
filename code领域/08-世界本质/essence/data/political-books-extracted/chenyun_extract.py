def render_quotes(hits):
    if not hits:
        return '_（本专题在原文中直接匹配结果较少，详见背景分析）_\n'
    lines = []
    for i, h in enumerate(hits, 1):
        lines.append(f"**{i}. 〔{h['vol']}·{h['phase']}｜第{h['page']}页｜《{h['article']}》〕**")
        lines.append('')
        lines.append(f"> {h['frag']}")
        lines.append('')
    return '\n'.join(lines)


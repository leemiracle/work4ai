# ---- 引用提取 ----
def build_quote(page, sent_idx, context=2, min_len=40, max_len=260, article=None):
    """以 sent_idx 为中心，扩展前后 context 句，构成引用片段"""
    sents = page['sents']
    lo = max(0, sent_idx - context)
    hi = min(len(sents), sent_idx + context + 1)
    # 向前/后扩展，直到长度合适
    frag = ''.join(s[2] for s in sents[lo:hi])
    # 若太长，收缩到中心
    while len(frag) > max_len and hi - lo > 1:
        if (sent_idx - lo) >= (hi - 1 - sent_idx):
            lo += 1
        else:
            hi -= 1
        frag = ''.join(s[2] for s in sents[lo:hi])
    # 若太短，尝试再扩
    while len(frag) < min_len and (lo > 0 or hi < len(sents)):
        if lo > 0: lo -= 1
        elif hi < len(sents): hi += 1
        else: break
        frag = ''.join(s[2] for s in sents[lo:hi])
    return clean_quote(frag, article)

def clean_quote(frag, article=None):
    """清洗页码/页脚/目录残留"""
    # 1) 去除"数字+字母标记+汉字" 如 "３０２B这是..."（页码+脚注标记）
    frag = re.sub(r'[０-９0-9]{1,4}[A-Za-zＡ-Ｚａ-ｚ](?=[\u4e00-\u9fff])', '', frag)
    # 1b) 去除"陈云文选第X卷"书名页脚（每页底部），及前面的页码数字
    frag = re.sub(r'[０-９0-9]{0,4}陈云文选第[一二三]卷$', '', frag)
    frag = re.sub(r'[０-９0-9]{0,4}陈云文选第[一二三]卷', '', frag)
    # 2) 去除"数字+文章名"页脚，如 "902实行粮食统购统销"、"742计划与市场问题"
    frag = re.sub(r'[０-９0-9]{1,3}(?=[\u4e00-\u9fff]{4,})', '', frag)
    # 3) 去除行首的孤立数字（页码）
    frag = re.sub(r'^[０-９0-9]{1,4}\s*', '', frag)
    # 4) 去除连续省略号（目录页特征 ⋯⋯⋯）
    if frag.count('⋯') >= 3:
        return ''
    # 5) 去除末尾突兀的文章名残留（页脚文章名被并入句尾）
    #    规则A：frag 以 article 结尾，且 article 前不是句末标点 → 截断
    #    规则B：frag 以 article 结尾，且 article 在全文仅出现 1 次（仅在末尾）→ 截断（页脚特征）
    if article and len(article) >= 4 and frag.endswith(article):
        prefix = frag[:-len(article)]
        truncate = False
        if prefix:
            if prefix[-1] not in '。！？：；））”」』':
                truncate = True  # 规则A
            elif frag.count(article) == 1:
                truncate = True  # 规则B：句号后紧跟仅出现一次的完整文章名=页脚
        if truncate:
            frag = prefix
    # 6) 同样处理 article 的前 6 字（页脚有时用简写）
    if article and len(article) >= 6:
        head6 = article[:6]
        if frag.endswith(head6) and len(frag) > len(head6) + 10:
            prefix = frag[:-len(head6)]
            if prefix and prefix[-1] not in '。！？：；））”」』':
                frag = prefix
    # 7) 去除开头的标题行残留："文章名B（一九...年）" 或 "文章名（一九...年）"
    frag = re.sub(r'^[\u4e00-\u9fff]{2,30}[A-Za-zＡ-Ｚａ-ｚ]?（一[八九０-９0-9]{2}年[０-９0-9]{1,2}月[０-９0-9]{1,2}日）', '', frag)
    frag = re.sub(r'^[\u4e00-\u9fff]{2,30}B（', '（', frag)  # 残留的"B（日期）"去掉文章名+B
    # 8) 截断编者注脚注混入（中间或末尾）：找到"这是陈云同志…的提纲/讲话/报告/信…"，截断到其前
    m = re.search(r'(这是|此文是|本篇是|这篇是)(陈云同志|陈云|此文).{0,45}(写的|所作的|在|给|和|联名).{0,30}(提纲|讲话|报告|信件|信|批语|发言|谈话|说明|意见|文章)[。.]?', frag)
    if m:
        frag = frag[:m.start()].rstrip('，、；：')
    # 9) 去除因截断/页脚剥离残留的末尾连接词/半个词
    if len(frag) >= 3:
        for tail in ('共产', '以及', '是否', '考虑国', '考虑', '用于重要轧', '动用库存多少', '制度中', '出现的主', '出现'):
            if frag.endswith(tail) and len(frag) > len(tail) + 20:
                frag = frag[:-len(tail)]
                break
    frag = frag.strip()
    # 10) 去除末尾悬空的连接标点（，、；：），使引用不以"断词+逗号"呈现
    while frag and frag[-1] in '，、；：':
        frag = frag[:-1].rstrip()
    return frag

def search_topic(keywords, article_hints=None, want=10, exclude_keywords=None,
                 vol_filter=None, page_range=None):
    """
    keywords: 主关键词列表（任一命中即候选）
    article_hints: 优先篇章标题片段列表（打分加权）
    返回按打分排序的引用列表
    """
    hits = []
    for pg in PAGES:
        if vol_filter and pg['vol'] not in vol_filter: continue
        if page_range and not (page_range[0] <= pg['page'] <= page_range[1]): continue
        nm = pg['norm']
        # 该页是否含任一关键词
        kw_hits = {kw: nm.count(kw) for kw in keywords}
        if sum(kw_hits.values()) == 0: continue
        # 排除
        if exclude_keywords and any(nm.count(x) > 0 for x in exclude_keywords):
            pass  # 不整体排除页，只在打分时处理
        # 篇章加权
        art_bonus = 0
        if article_hints and any(h in pg['article'] for h in article_hints):
            art_bonus = 3
        # 遍历句子
        for i, (s, e, st) in enumerate(pg['sents']):
            sent_kw = sum(st.count(kw) for kw in keywords)
            if sent_kw == 0: continue
            frag = build_quote(pg, i, article=pg['article'])
            # 清洗后为空或过短，跳过
            if not frag or len(frag) < 25:
                continue
            # 排除片段含强排除词
            if exclude_keywords and any(frag.count(x) > 0 for x in exclude_keywords):
                continue
            # 打分
            score = sent_kw * 2
            score += art_bonus
            # 长度适中加分
            if 60 <= len(frag) <= 240: score += 2
            elif len(frag) < 25: score -= 3
            # 多关键词共现加分
            distinct = sum(1 for kw in keywords if st.count(kw) > 0)
            score += distinct
            hits.append({
                'score': score,
                'vol': pg['vol'], 'page': pg['page'],
                'article': pg['article'], 'phase': pg['phase'],
                'frag': frag, 'distinct': distinct,
                'sent': st
            })
    # 去重：去标点后前40字相同者视为重复，保留分数高的
    def fingerprint(s):
        return re.sub(r'[^\u4e00-\u9fff]', '', s)[:40]
    hits.sort(key=lambda x: -x['score'])
    seen = set()
    uniq = []
    for h in hits:
        fp = fingerprint(h['frag'])
        if not fp: continue
        if fp in seen: continue
        seen.add(fp)
        uniq.append(h)
    return uniq[:want]


# -*- coding: utf-8 -*-
"""
诺奖物理学名录统计（走廊1：名录统计）
对应章：讲透物理学史/04-物理学史转代码.md

数据：1901-2025 诺贝尔物理学奖届年表（内嵌，届=颁奖年；未颁奖年标记 None）
领域标签仅对 2000-2025 逐届给出（本实验只断言有把握核实的部分）。
数据口径：2026-09 模型知识核对；如与 nobelprize.org 不符以官网为准。
"""
from collections import Counter

# 1901-2025 每年一届；未颁奖年份：1916, 1931, 1934, 1940, 1941, 1942
AWARD_YEARS = [y for y in range(1901, 2026)
               if y not in {1916, 1931, 1934, 1940, 1941, 1942}]

# 2000-2025 逐届领域粗分类（同届多人计一类；分类口径见 04 章走廊1）
FIELD_2000_2025 = {
    2000: "凝聚态", 2001: "AMO", 2002: "天体", 2003: "凝聚态", 2004: "粒子核",
    2005: "AMO",    2006: "天体", 2007: "凝聚态", 2008: "粒子核", 2009: "应用交叉",
    2010: "凝聚态", 2011: "天体", 2012: "AMO",    2013: "粒子核", 2014: "凝聚态",
    2015: "粒子核", 2016: "凝聚态", 2017: "天体",  2018: "AMO",    2019: "天体",
    2020: "天体",   2021: "应用交叉", 2022: "AMO", 2023: "AMO",   2024: "应用交叉",
    2025: "凝聚态",
}

def main():
    # 断言1：空缺年恰为两次大战/经济危机的六处（史料：诺奖官方年表）
    gaps = sorted(set(range(1901, 2026)) - set(AWARD_YEARS))
    assert gaps == [1916, 1931, 1934, 1940, 1941, 1942], gaps
    print(f"[1] 空缺年 = {gaps}  （1940-42 二战三连空缺——制度史证据）")

    # 断言2：125 个年份 - 6 空缺 = 119 届
    assert len(AWARD_YEARS) == 119, len(AWARD_YEARS)
    print(f"[2] 1901-2025 共颁奖 {len(AWARD_YEARS)} 届")

    # 断言3：2000-2025 领域分布——凝聚态与天体并列为最大板块
    c = Counter(FIELD_2000_2025.values())
    assert len(FIELD_2000_2025) == 26
    assert c["凝聚态"] >= 7 and c["天体"] >= 6 and c["AMO"] >= 5, c
    top = c.most_common()
    print(f"[3] 2000-2025 领域分布 = {dict(top)}")
    print("    → 凝聚态+AMO 合计占比 "
          f"{(c['凝聚态']+c['AMO'])/26:.0%}：物理学的'大部队'与仪器革命同源")

    print("\n全部断言通过 ✓ （名录统计=走廊1：把制度史变成可验证数据）")

if __name__ == "__main__":
    main()

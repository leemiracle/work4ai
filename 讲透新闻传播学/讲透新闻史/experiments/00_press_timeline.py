def slice_by_century(events):
    """世纪切片:取 ceil(year/100) 为桶键(713→8 世纪)。"""
    buckets = {}
    for year, region, tech, event in events:
        buckets.setdefault((year + 99) // 100, []).append((year, region, tech, event))
    return dict(sorted(buckets.items()))


def era_of(year):
    """年份→技术代标签(窗口闭区间)。"""
    for lo, hi, name in ERAS:
        if lo <= year <= hi:
            return name
    return OPEN_ERA[2]


def density(events, lo, hi):
    """[lo, hi] 闭区间内的事件密度(件/百年)。"""
    n = sum(1 for e in events if lo <= e[0] <= hi)
    span = hi - lo + 1
    return n, n / span * 100



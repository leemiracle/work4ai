# ============================================================
# 任务自动化潜力评估器
# ============================================================
# 5 个维度评分 (0=低潜力, 1=高潜力):
# - structured: 任务是否结构化 (有明确输入输出)
# - repetitive: 任务是否重复 (每次相似)
# - tolerance: 容错率 (错了一次没事 vs 一次就死)
# - creative:   创意度 (反向: 创意高 → 难自动化)
# - physical:   物理操作 (反向: 物理操作 → 难自动化)
# - ambiguity:  模糊性 (反向: 高模糊 → 难)

def automation_score(structured, repetitive, tolerance, creative, physical, ambiguity):
    """综合评分, 返回 0-1"""
    score = (
        0.25 * structured +
        0.20 * repetitive +
        0.20 * tolerance +
        0.15 * (1 - creative) +    # 反向
        0.10 * (1 - physical) +    # 反向
        0.10 * (1 - ambiguity)     # 反向
    )
    return max(0, min(1, score))


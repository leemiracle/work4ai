CH, RO, X = "CH", "RO", "X"
SYSTEM_LABELS = {CH: "中华法系", RO: "罗马法系", X: "两系相遇"}
SYSTEM_ORDER = [CH, RO, X]

DORMANCY = (534, 1069)      # 罗马休眠期窗口:533 之后、约1070 之前
WAVE = (1900, 1930)         # 两系合流窗口(修律-法典化)
BASELINE_END = 1799         # 基线窗口终点(两千年基线:前536-1799)


def slice_by_century(events):
    """世纪切片:公元/公元前分桶(无 0 年,负数=公元前)。"""
    buckets = {}
    for year, system, actor, text in events:
        bucket = -((abs(year) + 99) // 100) if year < 0 else (year + 99) // 100
        buckets.setdefault(bucket, []).append((year, system, actor, text))
    return dict(sorted(buckets.items()))


def century_label(bucket):
    if bucket > 0:
        return f"{bucket * 100 - 99}~{bucket * 100}"
    b = abs(bucket)
    return f"前{b * 100}~前{b * 100 - 99}"


def years_of(events, system=None):
    ys = [y for y, s, _, _ in events if system is None or s == system]
    return sorted(ys)


def max_gap(events, system):
    """最大事件间隔+位置(04 章 cliff 函数):断代/休眠的数据信号。"""
    ys = years_of(events, system)
    return max(((a, b, b - a) for a, b in zip(ys, ys[1:])), key=lambda t: t[2])


def density(events, lo, hi, system=None):
    """窗口密度:件/百年。"""
    n = sum(1 for y, s, _, _ in events
            if (system is None or s == system) and lo <= y <= hi)
    return n / max(hi - lo + 1, 1) * 100, n


def main():
    print("=" * 72)
    print(f"双法系大事编年:{len(TIMELINE)} 条里程碑 · 世纪×法系切片")
    print("=" * 72)

    # ── C1/C3 主表:世纪×法系 ────────────────────────────────
    centuries = slice_by_century(TIMELINE)
    print(f"\n{'年代区间':>14} {'中华':>4} {'罗马':>4} {'相遇':>4}   本窗口大事")
    for bucket, evs in centuries.items():
        by_sys = {s: sum(1 for _, ss, _, _ in evs if ss == s) for s in SYSTEM_ORDER}
        sample = evs[0][3][:24] + "…"
        print(f"{century_label(bucket):>14} {by_sys[CH]:>4} {by_sys[RO]:>4} {by_sys[X]:>4}   {sample}")

    totals = {s: sum(1 for _, ss, _, _ in TIMELINE if ss == s) for s in SYSTEM_ORDER}
    print("\n法系总计:", "  ".join(
        f"{SYSTEM_LABELS[s]}×{totals[s]}" for s in SYSTEM_ORDER))

    # ── 断言 1:罗马法休眠期(533→约1070 之间零事件,且为最大深谷)──
    dorm = [e for e in TIMELINE if e[1] == RO and DORMANCY[0] <= e[0] <= DORMANCY[1]]
    gap = max_gap(TIMELINE, RO)
    print("\n" + "=" * 72)
    print(f"休眠期检验:{DORMANCY[0]}-{DORMANCY[1]} 年罗马轨事件数 = {len(dorm)}")
    print(f"          罗马轨最大间隔 {gap[2]} 年({gap[0]}→{gap[1]})"
          "——《学说汇纂》编成后失传,至波伦亚重见")
    assert len(dorm) == 0, "休眠期内罗马轨不应有事件"
    assert gap[2] == 537 and gap[0] == 533, "罗马轨最大间隔应为 533→1070(537 年)"

    # ── 断言 2:两系合流窗口密度是两千年基线的十倍以上 ─────────
    d_base, n_base = density(TIMELINE, -536, BASELINE_END)
    d_wave, n_wave = density(TIMELINE, WAVE[0], WAVE[1])
    ratio = d_wave / d_base
    print(f"合流检验:基线 前536-{BASELINE_END} 共 {n_base} 件 = {d_base:.2f} 件/百年")
    print(f"          窗口 {WAVE[0]}-{WAVE[1]} 共 {n_wave} 件 = {d_wave:.2f} 件/百年")
    print(f"          密度比 = {ratio:.0f}× ——修律与法典化叠加的两系合流三十年")
    assert ratio >= 10, "合流窗口密度应比两千年基线高一个量级"
    assert n_wave >= 5, "1900-1930 应至少 5 条(修律+欧陆法典化密集)"

    # ── 断言 3:中华法系两千年无罗马级深谷 ────────────────────
    ch_gap = max_gap(TIMELINE, CH)
    print(f"无深谷检验:中华轨最大间隔 {ch_gap[2]} 年({ch_gap[0]}→{ch_gap[1]})"
          f" < 罗马休眠期 537 年")
    assert ch_gap[2] < 537, "中华轨不应出现罗马级深谷"
    span = years_of(TIMELINE, CH)
    assert span[-1] - span[0] >= 2400, "中华轨覆盖应超过两千四百年"

    # ── 断言 4:相遇轨在场(移植链的三条边,03 章 §6)─────────
    cross_years = [1864, 1911, 2020]
    cross = [e for e in TIMELINE if e[1] == X and e[0] in cross_years]
    assert len(cross) == 3, "相遇轨关键事件(术语/法典/当代)应齐"
    print(f"断言通过:相遇轨 {len(cross)} 条(1864 术语入场 → 1911 两系合流 → 2020 当代延续)✓")
    print("断言通过:休眠期零事件/合流密度比 %.0f×/无深谷 三组史学直觉全部拿到数据支撑 ✓"
          % ratio)


CENTURY_SPLIT = 1550          # 文艺复兴/符号爆炸的分界(00 章 §3 近代线起点附近)
DOMAIN_ORDER = ["代数", "几何", "数论", "分析", "中国", "概率", "统计", "逻辑",
                "计算", "离散", "拓扑", "运筹", "代数几何", "社区", "全景"]


def slice_by_century(events):
    """世纪切片:取 ceil(year/100) 为桶键(前2世纪→-1 桶等,Python 负数除法已对齐)。"""
    buckets = {}
    for year, domain, person, event in events:
        bucket = -((abs(year) + 99) // 100) if year < 0 else (year + 99) // 100
        buckets.setdefault(bucket, []).append((year, domain, person, event))
    return dict(sorted(buckets.items()))


def main():
    print("=" * 70)
    print("数学史大事编年:101 条里程碑 · 世纪×领域切片")
    print("=" * 70)

    centuries = slice_by_century(TIMELINE)
    print(f"\n{'世纪(公元)':>10} {'事件数':>6}   领域分布")
    for bucket, evs in centuries.items():
        label = f"{bucket * 100}-" if bucket >= 1 else f"前{abs(bucket) * 100}-"
        domains = {}
        for _, d, _, _ in evs:
            domains[d] = domains.get(d, 0) + 1
        top = ", ".join(f"{d}×{c}" for d, c in
                        sorted(domains.items(), key=lambda kv: -kv[1])[:4])
        print(f"{label:>12} {len(evs):>6}   {top}")

    # 领域全表:每个领域贡献了几件大事
    domain_total = {}
    for _, d, _, _ in TIMELINE:
        domain_total[d] = domain_total.get(d, 0) + 1
    print("\n领域总计:", "  ".join(
        f"{d}×{domain_total[d]}" for d in DOMAIN_ORDER if d in domain_total))

    # 断言 1:1550 后密度陡增(知识加速)
    pre = [e for e in TIMELINE if e[0] < CENTURY_SPLIT]
    post = [e for e in TIMELINE if e[0] >= CENTURY_SPLIT]
    pre_span = CENTURY_SPLIT - (-1800)              # 3350 年
    post_span = 2024 - CENTURY_SPLIT                # 474 年
    dens_pre, dens_post = len(pre) / pre_span, len(post) / post_span
    ratio = dens_post / dens_pre
    print("\n" + "=" * 70)
    print(f"密度比检验:{CENTURY_SPLIT} 年前 {len(pre)} 件/{pre_span} 年"
          f" = {dens_pre:.4f} 件/百年")
    print(f"          {CENTURY_SPLIT} 年后 {len(post)} 件/{post_span} 年"
          f" = {dens_post:.2f} 件/百年")
    print(f"          密度比 = {ratio:.0f}× —— 符号爆炸/印刷/期刊制度下的知识加速")
    assert ratio > 10, "文艺复兴后密度应高一个量级"

    # 断言 2:领域覆盖完备(四线家族树每线都有代表)
    for need in ("代数", "几何", "分析", "数论", "中国", "逻辑", "计算"):
        assert need in domain_total, f"领域 {need} 不应缺席"
    print("断言通过:七条主领域线全部有事件(四线分期各有实证)✓")

    # 断言 3:传播链事件在场(中心转移的可构造信号,03 章 §2.2)
    diffusion = [e for e in TIMELINE if e[0] in (820, 1202, 1545, 1916)]
    assert len(diffusion) >= 3, "传播链事件(820/1202/1545/1916)应在场"
    print(f"断言通过:传播链事件在场 {len(diffusion)} 条"
          "(820 al-jabr → 1202 数字入欧 → 1545 解之战 → 1916 几何凯旋)✓")


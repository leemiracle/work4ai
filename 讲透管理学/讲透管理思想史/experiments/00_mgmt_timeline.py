# 分期切片(六段;比 00 章 §3 的四支更细,便于密度检验)
ERAS = [
    ("前科学时代(1776-1910)", None, 1910),
    ("古典双奠基(1911-1932)", 1911, 1932),
    ("行为与决策转向(1933-1953)", 1933, 1953),
    ("学派爆炸(1954-1979)", 1954, 1979),
    ("战略与质量黄金期(1980-1999)", 1980, 1999),
    ("数字与AI(2000-)", 2000, None),
]

# 学派展示序(≈八阶段映射;闭集标签本身是史学判断,见 04 章 §2.1)
SCHOOL_ORDER = ["前史", "科学管理", "古典组织", "人本先驱", "人际-行为", "决策学派",
                "质量精益", "大师综合", "组织批判", "战略", "元理论", "系统权变",
                "知识学习", "中国线", "数字AI"]

CORE_SCHOOLS = ["科学管理", "古典组织", "人际-行为", "决策学派", "系统权变",
                "战略", "质量精益", "知识学习", "数字AI"]


def slice_by_era(events):
    """分期切片:按 ERAS 的 [lo, hi] 闭区间归桶。"""
    buckets = {}
    for year, school, person, concept in events:
        for name, lo, hi in ERAS:
            if (lo is None or year >= lo) and (hi is None or year <= hi):
                buckets.setdefault(name, []).append((year, school, person, concept))
                break
    return buckets


def main():
    if hasattr(sys.stdout, "reconfigure"):          # Windows 控制台编码防御
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    print("=" * 70)
    print(f"管理思想大事编年:{len(TIMELINE)} 条里程碑 · 分期×学派切片(1776-2025)")
    print("=" * 70)

    years = [e[0] for e in TIMELINE]
    assert years == sorted(years), "编年必须按年份升序排列"
    assert len(TIMELINE) >= 60, "断言失败:大事编年应≥60 条"

    eras = slice_by_era(TIMELINE)
    print(f"\n{'分期':<26} {'事件数':>4}   学派分布(前4)")
    for name, _, _ in ERAS:
        evs = eras.get(name, [])
        schools = {}
        for _, s, _, _ in evs:
            schools[s] = schools.get(s, 0) + 1
        top = ", ".join(f"{s}×{c}" for s, c in
                        sorted(schools.items(), key=lambda kv: -kv[1])[:4])
        print(f"{name:<30} {len(evs):>4}   {top}")

    # 学派全表:首发年 + 条数 + 活跃跨度
    school_stat = {}
    for year, school, _, _ in TIMELINE:
        s = school_stat.setdefault(school, {"count": 0, "first": year, "last": year})
        s["count"] += 1
        s["first"] = min(s["first"], year)
        s["last"] = max(s["last"], year)
    print("\n学派总计(首发年/条数/活跃跨度):")
    for s in SCHOOL_ORDER:
        if s in school_stat:
            st = school_stat[s]
            print(f"  {s:<8} 首发{st['first']}  {st['count']:>2} 条  "
                  f"{st['first']}-{st['last']}")

    # 断言 A:1911-1932 双奠基窗口密度陡增(对比 1776-1910)
    founding = [e for e in TIMELINE if 1911 <= e[0] <= 1932]
    pre = [e for e in TIMELINE if e[0] < 1911]
    f_span, p_span = 1932 - 1911 + 1, 1910 - 1776
    dens_f, dens_p = len(founding) / f_span, len(pre) / p_span
    ratio = dens_f / dens_p
    print("\n" + "=" * 70)
    print(f"断言A 双奠基密度:1911-1932 共 {len(founding)} 条/{f_span} 年"
          f" = {dens_f:.3f} 条/年")
    print(f"              1776-1910 共 {len(pre)} 条/{p_span} 年"
          f" = {dens_p:.3f} 条/年")
    print(f"              密度比 = {ratio:.1f}× —— 科学管理+古典组织+霍桑启动的密集奠基")
    assert ratio > 3, "双奠基窗口密度应高出数倍"

    # 断言 B:1950s 后学派爆炸(首发≥1950 的学派数 > 首发此前)
    post_schools = {s for s, st in school_stat.items() if st["first"] >= 1950}
    pre_schools = {s for s, st in school_stat.items() if st["first"] < 1950}
    print(f"\n断言B 学派爆炸:首发于 1950 前的学派 {len(pre_schools)} 个"
          f"({','.join(sorted(pre_schools))})")
    print(f"              首发于 1950 后的学派 {len(post_schools)} 个"
          f"({','.join(sorted(post_schools))})")
    assert len(post_schools) > len(pre_schools), "1950 后首发的学派应更多"
    print("              —— 孔茨丛林(1961/1980)所数的学派,大半是战后出生的")

    # 断言 C:1990s 后科技驱动事件(数字AI 学派全部晚于 1990 且≥10 条)
    tech = [e for e in TIMELINE if e[1] == "数字AI"]
    assert len(tech) >= 10 and all(e[0] > 1990 for e in tech), \
        "数字AI 事件应≥10 条且全部晚于 1990"
    print(f"\n断言C 科技驱动:『数字AI』学派 {len(tech)} 条全部落在 "
          f"{min(e[0] for e in tech)}-{max(e[0] for e in tech)} —— 2000s 后的新议程")

    # 断言 D:九条核心学派线在场(八阶段主线各有实证)
    for need in CORE_SCHOOLS:
        assert need in school_stat, f"核心学派 {need} 不应缺席"
    print("断言D 通过:九条核心学派线全部有事件(八阶段主线各有实证)✓")

    print("\n⚠ 史学纪律提醒:本表度量『正史关注度』而非『管理智慧产出』——")
    print("  删掉你最不服的一条大事重跑(敏感性分析)是使用本脚本的正确姿势(04 章 §0)。")
    print("  2020s 条目为『正在发生的历史』,检索校准 2026-09-07,生产期复核。")


if __name__ == "__main__":
    main()

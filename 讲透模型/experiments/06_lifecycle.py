"""
实验 06 — 生命周期: 模型作为可运维资产
对应文档: 讲透模型/06-生命周期.md

核心结论:
  1. 模型是资产不是交付物: 上线才是生命周期开始
  2. 六阶段各有决策门: 外购基座/改行为才调/自评不上线/SLA才部署/漂移必报警/三判据退役
  3. 三条死法: 上线即弃 / 永不退役 / 跳过自评
  4. 实测: 一个 [漂移 -> 质量退化 -> 触发退役] 的生命周期模拟

跑法: python3 -u 06_lifecycle.py
"""
import random
random.seed(0)

def P(*a): print(*a, flush=True)

P("="*70)
P("实验 06 — 生命周期: 模型作为可运维资产")
P("="*70)
P()

# ============================================================
# Part 1: 六阶段决策门
# ============================================================
P("Part 1: 六阶段决策门 — 每阶段的'过不过?'")
P("-"*70)
P()
stages = [
    ("① 预训练",  "千万$级",  "99% 团队直接跳过 -> 外购开源基座"),
    ("② 后训练",  "百$~百万$", "改行为才调 (SFT/DPO), 注知识走 RAG"),
    ("③ 评估",    "人天级",   "公开榜分 != 你的任务分 -> 自评不过不上线"),
    ("④ 部署",    "硬件+工程", "延迟/吞吐/成本三角达 SLA 才部署"),
    ("⑤ 监控",    "持续",     "golden set 回放 + 输入分布漂移报警"),
    ("⑥ 退役",    "迁移成本", "性价比/风险/能力债 三判据触发"),
]
for name, cost, gate in stages:
    P(f"  {name:10s} 成本 {cost:10s} | 决策门: {gate}")
P()
P("  关键: ①② 只占成本一小段, ④⑤⑥ 才是长尾 -> 选型定起点, 生命周期定总回报")
P()

# ============================================================
# Part 2: 漂移模拟 — 静默退化与退役触发
# ============================================================
P("Part 2: 漂移模拟 — 上线即弃的死法演示")
P("-"*70)
P()
P("  设定: 模型上线时质量 92%, 输入分布每月偏移, 质量缓慢侵蚀;")
P("  无监控 = 退化静默累积; 有监控 = 跌破阈值(85%)触发重评/退役")
P()

quality = 92.0
threshold = 85.0
month_log = []
for month in range(1, 25):
    drift = random.uniform(0.2, 0.9)          # 每月质量侵蚀
    quality -= drift
    alert = "  <-- 触发退役判据(跌破阈值)" if quality < threshold else ""
    month_log.append((month, quality, alert))
    if quality < threshold - 5:
        break

P("  月    质量    状态")
for m, q, a in month_log:
    bar = "#" * int(q / 2)
    P(f"  {m:2d}   {q:5.1f}  {bar}{a}")
P()
triggered = month_log[-1][1] < threshold
P(f"  结论: 第 {month_log[-1][0]} 个月质量 {month_log[-1][1]:.1f}% "
  f"{'已跌破阈值' if triggered else '仍在阈值上'}")
P("  无监控场景: 用户投诉先于指标崩; 有监控场景: 阈值报警 -> 走退役三判据")
P()

# ============================================================
# Part 3: 退役三判据 + TCO 骨架
# ============================================================
P("Part 3: 退役三判据 + 24 个月 TCO 骨架")
P("-"*70)
P()
P("  判据一 性价比: 新模型自评 +10pp 且 (迁移成本 < 12个月收益) -> 升级")
P("  判据二 风险:   安全漏洞 / 许可证变更 / 供应方停服 -> 强制迁移")
P("  判据三 能力债: 任务升级(如要工具调用), 老模型天花板不够 -> 升级或蒸馏")
P()
# 一个诚实的 TCO 骨架(占位数字标注为示例, 非实测)
tco = [
    ("后训练(一次性)",  20_000),
    ("自评集建设",       8_000),
    ("部署(2xA100 月租 x24)", 14_000*24),
    ("监控人力(0.2 FTE x24)", 6_000*24),
    ("12个月强制重评 x2",  15_000),
]
total = sum(c for _, c in tco)
P("  示例 TCO(占位数字, 非实测; 练习1 换成你的真实成本):")
for name, cost in tco:
    P(f"    {name:28s} ${cost:>12,}")
P(f"    {'合计(24个月)':28s} ${total:>12,}")
P()
P("  注意: 部署+监控占了 TCO 的大头 -> 印证 '④⑤⑥ 是长尾'")
P()

# ============================================================
# Part 4: 开源 vs API 的生命周期差异
# ============================================================
P("Part 4: 开源 vs API — 两种生命周期")
P("-"*70)
P()
P("  自部署: 你管全周期, 升级你定, 注册表可秒回滚, 死法=永不退役")
P("  API:    供应方管①②, 你管③⑤⑥, deprecated 通知=强制退役倒计时,")
P("          最易忽略监控项: 同一 prompt 输出分布随时间悄悄漂移")
P()

P("="*70)
P("一句话: 模型是资产 — 上线才是开始, 六道决策门 + 三判据退役,")
P("        三条死法: 上线即弃 / 永不退役 / 跳过自评")
P("="*70)

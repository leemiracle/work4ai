# 模拟: 4 种任务难度, 不同模型规模的"成本效益"
def task_score(difficulty, model_size):
    """难度 0-1, 模型 size (B); 返回 acc 估计"""
    # 难度越高, 需要的模型越大; 简单任务 7B 应已近 95%
    threshold = math.pow(difficulty, 1.5) * 50   # 难度 0.2 → 4.5B, 0.85 → 39B
    if model_size < threshold / 3:
        return 0.4 + (model_size / threshold) * 0.4
    elif model_size < threshold:
        return 0.7 + (model_size / threshold) * 0.2
    else:
        return min(0.98, 0.9 + math.log(max(model_size / threshold, 1)) * 0.03)

import math
print(f"{'任务难度':<14}{'7B':>10}{'13B':>10}{'70B':>10}{'405B':>10}{'最佳选择':<14}")
print("-"*68)
for diff, name in [(0.2, "闲聊/总结"), (0.4, "翻译/代码"), (0.6, "数学/Agent"), (0.85, "复杂推理")]:
    scores = {size: task_score(diff, size) for size in [7, 13, 70, 405]}
    best = max(scores, key=scores.get)
    row = f"{name:<14}"
    for size in [7, 13, 70, 405]:
        row += f"{scores[size]:>10.1%}"
    row += f"    {best}B"
    print(row)


"""
实验 02 — CoT 思维链: 分步推理为何比直接答准
对应文档: 讲透Prompt/02-CoT思维链.md
核心结论:
  1. CoT 本质是【分治】: 把一次复杂推理拆成多次简单推理, 每步 token 预测更易
  2. 直接答 = 一步预测最终结果(信息要全部综合, 难); CoT = 每步只做简单运算(易)
  3. CoT 是涌现能力: 小模型上 CoT 无效甚至变差(Wei 2022), 大模型才受益
  4. Zero-shot CoT: 一句"让我们一步步思考"就能激发, 无需示范
跑法: python3 -u 02_cot.py
"""
def P(*a): print(*a, flush=True)

P("="*60); P("Part 1: CoT 本质 = 分治 (把难题拆成简单子问题)"); P("="*60)
P("数学类比: 算 17 × 24")
P("  直接算: 17×24 = ?    (要同时处理多位, 认知负荷大, 易错)")
P("  分步算(CoT):")
P("    17×24 = 17×20 + 17×4")
P("    17×20 = 340")
P("    17×4  = 68")
P("    340+68 = 408")
P("每步都是简单运算, 难度大幅降低. 这就是 CoT 的核心.\n")

P("="*60); P("Part 2: 从 token 预测看 CoT 为何有效"); P("="*60)
P("LLM 是 token-by-token 预测. 看应用题'5个苹果吃2个又给3个, 现在几个?':")
P("  直接答: 输入[问题] → 预测'6'")
P("    这一步要把'5,-2,+3'全部综合成6, 单次预测信息密度高, P(6|问题)可能不高")
P("  CoT答: 输入[问题] → 预测'5-2=3' → 预测'3+3=6'")
P("    每步只做一个简单运算, P('3+3=6'|前文) 高(因为是简单算术)")
P("==> CoT 把'一次难预测'拆成'多次易预测', 每步条件更充分, 累积起来更准.")
P("    额外好处: 中间步骤写在上下文里, 后续步骤能'看到'(扩展了有效计算).\n")

P("="*60); P("Part 3: CoT 是涌现 —— 小模型用 CoT 反而更差"); P("="*60)
P("Wei et al. 2022 (Chain-of-Thought Prompting) 的发现:")
P("  小模型(<10B): CoT 几乎无效, 甚至比直接答更差(分步反而引入错误)")
P("  大模型(~60B+): CoT 在数学/逻辑/多步推理上大幅提升准确率")
P("  例: GSM8K 数学题, PaLM-540B 直接答 18% → CoT 56%")
P("为什么是涌现? 推理需要模型'维持中间状态+按规则推演', 这需要足够容量.")
P("(呼应 讲透基础模型/03: CoT 推理是真实相变, 非度量幻觉)\n")

P("="*60); P("Part 4: Zero-shot CoT —— 一句咒语"); P("="*60)
P("Zero-shot CoT (Kojima 2022): 不放示范, 只在问题后加一句:")
P('  "让我们一步步思考 (Let\'s think step by step)"')
P("GSM8K 准确率: 直接 17% → 加这句 60%+ (GPT-3.5)")
P("==> 仅仅触发'分步模式', 模型就自发展开推理. 这是最便宜的性能提升之一.\n")

P("="*60); P("CoT 的局限"); P("="*60)
P("  ① 消耗更多 token(分步输出长, 推理更贵更慢)")
P("  ② 不是万能: 事实性问题/简单任务 CoT 无益甚至干扰")
P("  ③ 可能'编造'推理链: 模型先有答案再补看似合理的步骤(rationalization)")
P("  ④ 小模型无效(必须大模型)")
P("==> CoT 适合多步推理(数学/逻辑/规划), 不适合事实检索/简单分类.")

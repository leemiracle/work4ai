ENLIGHTEN_SCHOOLS = ("数理学派", "检验决策")   # KPF 及其直接下游


def slice_by_century(events):
    """世纪切片:取 ceil(year/100) 为桶键(1603→17 世纪)。"""
    buckets = {}
    for year, school, person, event in events:
        buckets.setdefault((year + 99) // 100, []).append((year, school, person, event))
    return dict(sorted(buckets.items()))


def density(events, lo, hi):
    """[lo, hi] 闭区间内的事件密度(件/百年)。"""
    n = sum(1 for e in events if lo <= e[0] <= hi)
    span = hi - lo + 1
    return n, n / span * 100


def main():
    try:  # Windows 控制台中文输出保险(纯标准库)
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass

    print("=" * 70)
    print("统计学史大事编年:83 条里程碑 · 世纪×学派切片")
    print("=" * 70)

    centuries = slice_by_century(TIMELINE)
    print(f"\n{'世纪':>8} {'事件数':>6}   学派分布(前四)")
    for bucket, evs in centuries.items():
        schools = {}
        for _, s, _, _ in evs:
            schools[s] = schools.get(s, 0) + 1
        top = ", ".join(f"{s}×{c}" for s, c in
                        sorted(schools.items(), key=lambda kv: -kv[1])[:4])
        print(f"{bucket * 100:>9} {len(evs):>6}   {top}")

    # 学派全表:每个学派贡献了几件大事
    school_total = {}
    for _, s, _, _ in TIMELINE:
        school_total[s] = school_total.get(s, 0) + 1
    print("\n学派总计:", "  ".join(
        f"{s}×{school_total[s]}" for s in SCHOOL_ORDER if s in school_total))

    # 断言 1:1662 年(Graunt 死亡表)后密度陡增——统计学方法零点
    n_pre, dens_pre = density(TIMELINE, min(e[0] for e in TIMELINE), FOUNDMG_YEAR - 1)
    n_post, dens_post = density(TIMELINE, FOUNDMG_YEAR, max(e[0] for e in TIMELINE))
    ratio = dens_post / dens_pre
    print("\n" + "=" * 70)
    print(f"密度比检验:{FOUNDMG_YEAR} 年前 {n_pre} 件 = {dens_pre:.2f} 件/百年")
    print(f"          {FOUNDMG_YEAR} 年后 {n_post} 件 = {dens_post:.2f} 件/百年")
    print(f"          密度比 = {ratio:.1f}× —— Graunt 之后,统计才成为持续生产的方法")
    assert ratio > 4, "1662 年后事件密度应显著陡增"

    # 断言 2:KPF 学派 1880-1935 高密度 = Stigler「统计启蒙」的实证
    kpf = [e for e in TIMELINE
           if ENLIGHTEN_LO <= e[0] <= ENLIGHTEN_HI and e[1] in ENLIGHTEN_SCHOOLS]
    _, dens_window = density(TIMELINE, ENLIGHTEN_LO, ENLIGHTEN_HI)
    w_ratio = dens_window / dens_post
    print(f"\n统计启蒙检验:1880-1935 窗口内 KPF 及其下游 {len(kpf)} 件"
          f"(数理学派+检验决策)")
    print(f"          窗口总密度 {dens_window:.1f} 件/百年 ≈ 全期基准的 {w_ratio:.1f}×")
    print("          —— Stigler(1986)「统计启蒙 1885-1935」框架的数据侧回声")
    assert len(kpf) >= 25, "KPF 窗口事件数应 ≥25(统计启蒙)"
    assert w_ratio >= 2.0, "窗口密度应至少为全期基准的 2 倍"

    # 断言 3:学派覆盖完备 + 双中心人物 + 优先权事件在场
    for need in SCHOOL_ORDER:
        assert need in school_total and school_total[need] >= 1, f"学派 {need} 不应缺席"
    pearson = sum(1 for e in TIMELINE if "Pearson" in e[2])
    fisher = sum(1 for e in TIMELINE if "Fisher" in e[2])
    priority = [e[0] for e in TIMELINE if e[0] in (1805, 1809)]
    print(f"\n断言通过:十条学派线全部有事件(四波浪潮各有实证)✓")

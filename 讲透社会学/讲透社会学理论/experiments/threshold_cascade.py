# -*- coding: utf-8 -*-
"""阈值级联模拟:Granovetter(1978)集体行为阈值模型的最小实现。

00-体系结构.md(反直觉:集体结局由阈值分布形状而非均值决定)、
03-可构造与结构.md(阈值分布→集体结局的严格可构造性)、04-社会学理论转代码.md
(走廊 1/2)的配套实验。纯标准库(random),无第三方依赖。

模型:n 人各有一个加入阈值 τᵢ——已加入比例达到 τᵢ 时,i 才加入。
外生冲击给定种子 x₀(已加入者不退出),每步
    x_{t+1} = max( #{i: τᵢ ≤ x_t} / n , x_t )
即「被当前参与率唤起的比例」与「已加入比例」取大——序列单调不减、
有上界 1,必收敛到不动点 x*(满足 F(x*) ≤ x*)。整条命运只由阈值分布
{τᵢ} 与种子 x₀ 决定;Granovetter 的原意:集体结局不可还原为个体倾向的
平均数——要看分布的形状(哪一团挨着种子、后一团够不够得着前团的脚印)。

四幕:
  幕一 同均值不同形状,三种命运(n=100,种子 x₀=0.10,均值全为 0.40):
      A=[0.10]×40+[0.60]×60 → 稳态 40%(0.10 团被唤起,0.60 团够不着)
      B=[0.20]×50+[0.60]×50 → 稳态 10%(种子孤悬:无人阈值 ≤0.10)
      D=[0.10]×20+[0.475]×80 → 稳态 20%(唤起链更短)
      断言:均值相等而稳态 40%/10%/20% 各不相同——决定结局的是形状不是均值。
  幕二 完全级联 vs 完全沉默:
      E=[0.10]×40+[0.40]×60(均值 0.28,低于前三者)→ 种子 10% 唤起
      0.10 团(→40%),40% 恰好够到 0.40 团(→100%)。断言:E 稳态=100%
      ——均值更低反而全员卷入:链式覆盖比平均倾向重要。
  幕三 种子规模的相变(分布 B):
      种子 0.10 → 稳态 10%;种子 0.22(只多 12 个百分点)→ 稳态 50%
      (0.20 团 50 人被整体唤起)。相变边界恰在第二团阈值 0.20:
      x₀<0.20 时稳态=种子本身,x₀≥0.20 时稳态跳至 50%。
      断言:微小的外生冲击差异 × 分布形状 = 集体结局跳档。
  幕四 同均值随机形状的命运谱(蒙特卡洛,固定种子 20260907):
      抽两千个「均值 0.28 的两点分布」(低阈值 a∈[0.02,0.26]、低团人数
      k∈[10,90],高阈值 b=(28−k·a)/(100−k) 补齐均值),同一粒种子 x₀=0.10
      各自跑级联。断言:命运谱跨度 ≥0.8,且「全员级联(=1.00)」与
      「种子孤悬(=0.10)」并存——均值固定,形状自由,结局天差地别。

跑法: python3 -u experiments/threshold_cascade.py
"""

import random

N = 100       # 群体规模
SEED0 = 0.10  # 外生冲击:10% 的人已加入(最先动手的少数/首发采用者)


def cascade(thresholds, x0, max_steps=1000):
    """阈值级联:返回(轨迹, 稳态)。

    x_{t+1} = max( #{i: τᵢ ≤ x_t} / n , x_t );单调不减有上界,
    有限步内到不动点。轨迹含种子,并以不动点收尾(至少出现一次)。
    """
    n = len(thresholds)
    xs = [x0]
    for _ in range(max_steps):
        x = xs[-1]
        nxt = max(sum(1 for t in thresholds if t <= x) / n, x)
        xs.append(nxt)
        if nxt == x:
            break
    return xs, xs[-1]


def fmt_traj(xs):
    """轨迹打印:去掉末尾重复的不动点,箭头串联。"""
    core = xs[:-1] if len(xs) >= 2 and xs[-1] == xs[-2] else xs
    return " → ".join(f"{v:.2f}" for v in core) + f" → {xs[-1]:.2f}(不动点)"


# ==================== 幕一:同均值不同形状,三种命运 ====================

def act1():
    print("=" * 84)
    print("幕一 同均值不同形状,三种命运(种子 x₀=0.10;n=100;均值全为 0.40)")
    print("=" * 84)
    dists = {
        "A": [0.10] * 40 + [0.60] * 60,
        "B": [0.20] * 50 + [0.60] * 50,
        "D": [0.10] * 20 + [0.475] * 80,
    }
    desc = {
        "A": "[0.10]×40 + [0.60]×60",
        "B": "[0.20]×50 + [0.60]×50",
        "D": "[0.10]×20 + [0.475]×80",
    }
    out = {}
    for name, ts in dists.items():
        mean = sum(ts) / len(ts)
        traj, steady = cascade(ts, SEED0)
        out[name] = (mean, traj, steady)
        print(f"\n分布 {name} = {desc[name]}  均值 {mean:.2f}  稳态 {steady:.0%}")
        print(f"    轨迹:{fmt_traj(traj)}")
    print("\n读数:")
    print("  · A:0.10 团 40 人被种子直接唤起(0.10≤0.10)→ 参与率 40%;")
    print("    但 0.60 团的门槛远在上方,唤起链到此为止")
    print("  · B:没有任何人的阈值 ≤0.10——种子唤不起一个人,参与率冻结在")
    print("    种子本身:平均倾向 0.40 的群体,对 10% 的冲击完全沉默")
    print("  · D:只有 20 人贴着种子,唤起链更短——稳态 20%")
    print("  · 三个群体「平均激进程度」完全相同(0.40),结局 40%/10%/20% 三种命运:")
    print("    决定集体结局的是阈值分布的形状,不是均值")

    # 断言 1:均值相等而稳态各不相同
    for name in "ABD":
        assert abs(out[name][0] - 0.40) < 1e-12, f"分布 {name} 均值应为 0.40"
    assert abs(out["A"][2] - 0.40) < 1e-9, "A 稳态应为 40%"
    assert abs(out["B"][2] - 0.10) < 1e-9, "B 稳态应为 10%"
    assert abs(out["D"][2] - 0.20) < 1e-9, "D 稳态应为 20%"
    assert len({round(out[k][2], 6) for k in "ABD"}) == 3, "三者稳态应互不相同"
    print(f"\n✓ 幕一断言通过:均值同为 0.40,稳态 "
          f"{out['A'][2]:.0%}/{out['B'][2]:.0%}/{out['D'][2]:.0%} 各不相同"
          "——形状,不是均值,决定集体命运")
    return out


# ==================== 幕二:完全级联 vs 完全沉默 ====================

def act2():
    print("\n" + "=" * 84)
    print("幕二 完全级联 vs 完全沉默(均值更低,卷入更全)")
    print("=" * 84)
    E = [0.10] * 40 + [0.40] * 60
    mean_E = sum(E) / N
    traj, steady = cascade(E, SEED0)
    print(f"\n分布 E = [0.10]×40 + [0.40]×60,均值 {mean_E:.2f}(低于幕一三家的 0.40),"
          f"种子 x₀={SEED0:.2f}")
    print(f"轨迹:{fmt_traj(traj)}")
    print("\n读数:")
    print("  · 第一跳:0.10 团 40 人被种子唤起 → 参与率 40%")
    print("  · 第二跳:0.40 团的门槛恰好被 40% 覆盖 → 参与率 100%")
    print("  · 对照幕一的 B(均值 0.40,稳态 10%):均值更低的 E 反而全员卷入——")
    print("    链式覆盖(每团恰好踩进前一团的脚印)比平均倾向重要")

    # 断言 2:均值更低却完全级联
    assert mean_E < 0.40, "E 的均值应低于 0.40"
    assert abs(steady - 1.0) < 1e-9, "E 应完全级联到 100%"
    assert len(traj) == 4, "E 的轨迹应为 0.10 → 0.40 → 1.00 → 不动"
    print(f"\n✓ 幕二断言通过:E 均值 {mean_E:.2f} 低于前三者,稳态却 =100%"
          "——全员卷入靠的是链式覆盖,不是平均倾向")


# ==================== 幕三:种子规模的相变 ====================

def act3():
    print("\n" + "=" * 84)
    print("幕三 种子规模的相变(分布 B=[0.20]×50+[0.60]×50)")
    print("=" * 84)
    B = [0.20] * 50 + [0.60] * 50
    print(f"\n{'种子 x₀':>8} {'稳态':>6}  读数")
    out = {}
    for x0 in (0.10, 0.19, 0.20, 0.21, 0.22, 0.30):
        _, steady = cascade(B, x0)
        out[x0] = steady
        if steady <= x0 + 1e-12:
            note = "种子孤悬:F(x₀)=0,稳态=种子本身"
        else:
            note = "0.20 团 50 人被整体唤起,稳态=50%"
        print(f"{x0:>8.2f} {steady:>6.2f}  {note}")
    print("\n读数:")
    print("  · 相变边界恰在 0.20(第二团的阈值):x₀=0.19 时无人被唤起")
    print("    (0.20>0.19),稳态=种子;x₀ 一过 0.20,种子本身就够到 0.20 团,")
    print("    稳态跳到 50%——临界种子规模不是渐变的斜坡,是一道门槛")
    print("  · 种子只多 12 个百分点(0.10→0.22),集体结局从 10% 跳到 50%:")
    print("    微小的外生冲击差异 × 分布形状 = 集体结局跳档")

    # 断言 3:种子 0.10→0.22,稳态 10%→50%
    assert abs(out[0.10] - 0.10) < 1e-9, "种子 0.10 的稳态应为 10%"
    assert abs(out[0.22] - 0.50) < 1e-9, "种子 0.22 的稳态应为 50%"
    assert abs(out[0.19] - 0.19) < 1e-9, "边界之下(0.19)稳态应=种子"
    assert abs(out[0.20] - 0.50) < 1e-9, "边界之上(0.20)稳态应跳至 50%"
    assert out[0.22] - out[0.10] >= 0.39, "稳态跳档幅度应清晰可读"
    print(f"\n✓ 幕三断言通过:种子 0.10→0.22(+12 个百分点),稳态 "
          f"{out[0.10]:.0%}→{out[0.22]:.0%};相变边界=第二团阈值 0.20")


# ============ 幕四:同均值随机形状的命运谱(蒙特卡洛,固定种子) ============

def act4():
    print("\n" + "=" * 84)
    print("幕四 同均值随机形状的命运谱(均值 0.28;2000 次抽取,固定种子)")
    print("=" * 84)
    rng = random.Random(20260907)
    mean_fixed = 0.28
    trials = 2000
    full = frozen = partial = 0
    steadies = []
    for _ in range(trials):
        k = rng.randint(10, 90)                    # 低阈值团人数
        a = rng.uniform(0.02, 0.26)                # 低阈值(可行域内)
        b = (mean_fixed * N - k * a) / (N - k)     # 高阈值:补齐均值
        steady = cascade([a] * k + [b] * (N - k), SEED0)[1]
        steadies.append(steady)
        if steady >= 0.999:
            full += 1
        elif steady <= SEED0 + 1e-9:
            frozen += 1
        else:
            partial += 1
    spread = max(steadies) - min(steadies)
    print(f"\n两千个「均值 {mean_fixed:.2f}」的两点分布,同一粒种子 x₀={SEED0:.2f}:")
    print(f"  全员级联(稳态=1.00):{full:>4} 个形状")
    print(f"  部分唤起(0.10<稳态<1.00):{partial:>4} 个形状")
    print(f"  种子孤悬(稳态=0.10):{frozen:>4} 个形状")
    print(f"  命运谱:{min(steadies):.2f} ~ {max(steadies):.2f}(跨度 {spread:.2f})")
    print("\n读数:")
    print("  · 均值被钉死在 0.28,命运谱却从 0.10 铺到 1.00——「平均倾向」对")
    print("    集体结局几乎没有约束力;有约束力的是团与团的衔接(前团踩出的")
    print("    参与率是否够到后团的门槛)")
    print("  · 完全级联是刀锋形状:一团贴着种子、下一团恰好被踩到——幕二的 E")
    print("    全员卷入,靠的正是 0.40 恰好等于 40/100 这一脚精确的衔接")

    # 断言 4:命运谱跨度大,两级并存(固定种子可复现)
    assert full >= 10, f"应存在足量全员级联形状,实测 {full}"
    assert frozen >= 200, f"应存在足量种子孤悬形状,实测 {frozen}"
    assert spread >= 0.8, f"命运谱跨度应 ≥0.8,实测 {spread:.2f}"
    print(f"\n✓ 幕四断言通过:级联 {full} 例与孤悬 {frozen} 例并存,跨度 {spread:.2f}"
          "——均值固定,形状自由,结局天差地别")


def main():
    act1()
    act2()
    act3()
    act4()
    print("\n" + "=" * 84)
    print("总断言收口:")
    print("  ① 同均值(0.40)不同形状 → 稳态 40%/10%/20%:决定集体结局的是阈值")
    print("     分布的形状,不是平均倾向(微观倾向→宏观结局的聚合不可还原为均值)")
    print("  ② 均值更低(0.28)的 E 反而全员级联(稳态 100%):链式覆盖比平均倾向重要")
    print("  ③ 种子 0.10→0.22(+12 个百分点),分布 B 的稳态 10%→50% 跳档:")
    print("     相变边界=第二团阈值 0.20——微小外生冲击×分布形状=集体结局跳档")
    print("  ④ 两千个同均值形状的命运谱跨度 ≥0.8,级联与孤悬并存(固定种子可复现)")
    print("✓ 全部自验证通过")


if __name__ == "__main__":
    main()
